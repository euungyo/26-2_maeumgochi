#!/usr/bin/env python3
"""Make ko_font.h: a small 16 px bitmap font that contains ONLY the characters used in the UI code.
Usage:  python3 make_korean_font.py scenes_demo.h screens_demo.h ko_font.h
Run it again whenever you add new text to the screens. Font: GNU Unifont (pixel font, 16 px)."""
import re, sys
from PIL import Image, ImageDraw, ImageFont
FONT = '/usr/share/fonts/opentype/unifont/unifont_jp.otf'   # change this path on your computer
srcs, out = sys.argv[1:-1], sys.argv[-1]
chars = set(chr(c) for c in range(32, 127))
for fn in srcs:
    for line in open(fn, encoding='utf8'):
        if line.lstrip().startswith('#include'): continue
        for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', line):
            chars.update(ch for ch in m.group(1) if ch >= ' ')
f = ImageFont.truetype(FONT, 16)
glyphs, data = [], bytearray()
for ch in sorted(chars):
    w = 16 if f.getlength(ch) >= 12 else 8
    im = Image.new('L', (w, 16), 0); d = ImageDraw.Draw(im); d.fontmode = '1'
    d.text((0, 0), ch, font=f, fill=255)
    off = len(data)
    for y in range(16):
        for bx in range(w // 8):
            b = 0
            for k in range(8):
                b = (b << 1) | (1 if im.getpixel((bx * 8 + k, y)) > 127 else 0)
            data.append(b)
    glyphs.append((ord(ch), w, off))
with open(out, 'w') as o:
    o.write('// ko_font.h - generated by make_korean_font.py (GNU Unifont 16 px glyphs). Do not edit by hand.\n#pragma once\n#include <stdint.h>\nnamespace maeum { namespace ko_data {\n')
    o.write('struct Glyph { uint16_t cp; uint8_t w; uint16_t off; };\n')
    o.write('static const Glyph GLYPHS[] = {\n' + ',\n'.join('  {0x%04X, %d, %d}' % g for g in glyphs) + '\n};\n')
    o.write('static const int GLYPH_COUNT = %d;\n' % len(glyphs))
    o.write('static const uint8_t BITS[] = {\n')
    for i in range(0, len(data), 24): o.write('  ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',\n')
    o.write('};\n}}  // namespace\n')
print('glyphs:', len(glyphs), 'bytes:', len(data))
